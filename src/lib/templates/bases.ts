/**
 * 打印用的令牌：不管是哪套基底，落到纸上都是白底黑字。
 * 字体、字号、疏密、骨架保留，只把颜色、底纹和动效换掉——PDF 与页面同源渲染，不是二次排版。
 */
export function toPrintBase(base: BaseTokens): BaseTokens {
  return {
    ...base,
    color: {
      bg: "#ffffff",
      surface: "#fafafa",
      band: "#ffffff",
      ink: "#111111",
      ink2: "#333333",
      muted: "#666666",
      line: "#dcdcdc",
      accent: "#111111",
      onAccent: "#ffffff",
      accentSoft: "#f2f2f2",
    },
    shape: { radius: "0px", borderWidth: "1px" },
    motion: "none",
    /** 纸上没有轮盘：翻页壳一律落回长页，否则只会印出当前那一格 */
    shell: "stack",
    primitives: [],
    dna: { ...base.dna, texture: "none", ornament: "none", card: "flat" },
  };
}
