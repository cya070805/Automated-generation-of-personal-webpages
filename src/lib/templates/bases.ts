/**
 * 六套基底。
 *
 * 基底不是模板，也不是皮肤：它同时决定「气质」（颜色、字、圆角、疏密）
 * 和「骨架」（首屏是什么形、章节号长什么样、标题摆哪、底纹、装饰、卡片）。
 *
 * 为什么要有骨架这一层：
 * 只换颜色和字体，六套基底在缩略图里、在生成出来的页面里都是一个东西——
 * 用户看不出区别，也就没有「选基底」这件事的价值。所以每套基底拿一个
 * 只有它才有的页型：纸面归档 / 终端窗口 / 杂志报头 / 画廊图版 / 深色舞台 / 格子看板。
 *
 * 想加一套，照抄一份、改令牌、改 dna，再去配方表里给它挑讲法。
 */

