import { cn } from "@/lib/utils";

export const Input = React.forwardRef<
  HTMLInputElement,
  React.InputHTMLAttributes<HTMLInputElement>
>(({ className, type = "text", ...props }, ref) => (
  <input
    ref={ref}
    type={type}
    className={cn(
      "flex h-10 w-full rounded-lg border border-line-strong bg-bg px-3 text-[14px] text-ink transition-colors placeholder:text-faint focus-visible:border-accent/60 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent/15 disabled:cursor-not-allowed disabled:bg-subtle disabled:opacity-60",
      className,
    )}
    {...props}
  />
));
Input.displayName = "Input";

